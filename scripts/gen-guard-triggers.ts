#!/usr/bin/env tsx
/**
 * Write the `search_and_guards` migration (`M1-T13`; `02` §3.4, §3.5, §3.2 D5).
 *
 * Drizzle cannot express a virtual table or a trigger, so the FTS5 tables, the FTS sync triggers,
 * the I4 label triggers and the immutability triggers live in a **custom** migration. This script
 * generates it from the schema, which is the whole point: there are 31 labeled columns, so
 * hand-writing 62 near-identical I4 triggers guarantees that one is subtly different and that a
 * table added later has none at all.
 *
 * ## Usage
 *
 *   pnpm tsx scripts/gen-guard-triggers.ts            # write the migration
 *   pnpm tsx scripts/gen-guard-triggers.ts --check    # exit 1 if the committed file is stale
 *
 * `--check` is what keeps the generator honest, and it runs as a **test**
 * (`packages/storage/src/schema/guards.int.test.ts`) rather than as a `pnpm verify` step, so it is
 * exercised by `pnpm test` and by CI's dist-free jobs without lengthening the verify chain.
 * Without it, a labeled table added later would compile, pass review, and silently ship with no
 * I4 guard — which is the failure mode this whole file exists to make impossible.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  allGroupAgreementTriggers,
  allGroupImmutableTriggers,
  allI4Triggers,
  allImmutabilityTriggers,
} from '../packages/storage/src/schema/guards.sql.js';
import {
  allFtsTriggers,
  CREATE_FTS_TABLES,
  SECURE_DELETE_STATEMENTS,
} from '../packages/storage/src/schema/search.sql.js';

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/**
 * The committed migration.
 *
 * drizzle-kit 0.31.11 uses a flat `NNNN_name.sql` layout with a `meta/_journal.json`, not the
 * folder-per-migration layout `14`'s artefact path suggests — that is drizzle-kit v1's, which
 * `02` D16 defers to M14. Our own runner reads both (`M1-T14`).
 */
export const MIGRATION_PATH = 'packages/storage/migrations/0001_search_and_guards.sql';

/** drizzle's statement separator. The runner splits on it. */
const BREAKPOINT = '--> statement-breakpoint';

/** A banner, so nobody edits the file by hand without noticing. */
const HEADER = [
  '-- Generated by scripts/gen-guard-triggers.ts. Do not edit by hand.',
  '--',
  '-- FTS5 tables and sync triggers (02 §3.4), I4 label and parent-group triggers (02 §3.2 D5)',
  '-- and the immutability/append-only triggers (02 §3.3). Regenerate with:',
  '--   pnpm tsx scripts/gen-guard-triggers.ts',
  '-- `guards.int.test.ts` fails if this file is stale.',
].join('\n');

/** Every statement of the migration, in dependency order. */
export function migrationStatements(): readonly string[] {
  return [
    // Tables before the triggers that write to them.
    ...CREATE_FTS_TABLES,
    // `secure-delete` before any row exists, so no token is ever written under the lax setting.
    ...SECURE_DELETE_STATEMENTS,
    ...allFtsTriggers(),
    ...allI4Triggers(),
    // The other half of I4: a label belongs to the row's group, **and** every parent the row
    // points at belongs to it too. A plain foreign key checks existence, not agreement.
    ...allGroupAgreementTriggers(),
    // After the I4 triggers and before the table-level immutability ones: a `group_id` move is an
    // I4 violation reached through a parent, so it belongs with its own family.
    ...allGroupImmutableTriggers(),
    ...allImmutabilityTriggers(),
  ];
}

/** The migration file's exact contents. */
export function renderMigration(): string {
  const body = migrationStatements()
    .map((statement) => `${statement.trimEnd()};`)
    .join(`\n${BREAKPOINT}\n`);
  return `${HEADER}\n\n${body}\n`;
}

function main(argv: readonly string[]): number {
  const path = resolve(REPO_ROOT, MIGRATION_PATH);
  const rendered = renderMigration();
  if (argv.includes('--check')) {
    const current = readFileSync(path, 'utf8');
    if (current === rendered) {
      process.stdout.write(`${MIGRATION_PATH} is up to date\n`);
      return 0;
    }
    process.stderr.write(
      `${MIGRATION_PATH} is stale. Run: pnpm tsx scripts/gen-guard-triggers.ts\n`,
    );
    return 1;
  }
  writeFileSync(path, rendered);
  process.stdout.write(
    `wrote ${MIGRATION_PATH} (${String(migrationStatements().length)} statements)\n`,
  );
  return 0;
}

// `import.meta.main` is Node 24+; this file is also imported by its test, which must not run main.
if (import.meta.main) {
  process.exitCode = main(process.argv.slice(2));
}
